// A family-level Doc space (Platform-by-platform walkthrough): "<Family>
// Cloud", Cloud only, with each product's Cloud content as a Cloud part that
// lives in the part's own directory of the same Content repo. The converter
// writes only its family-level pages: the overview (`layout: overview`), built
// from the family's legacy home page (the cards a theme template drew from
// extra.home_page_cards), with one product card per Cloud part. Links into a part
// are docs:<part>/cloud/<page>/ links, which resolve to the platform's Cloud
// address (URLs, `latest` and canonicals: /<platform>/cloud/<part>/<page>/).
//
// The part is converted first, on the same branch: its redirects.yaml maps
// each legacy URL to its new page, which is how a card finds its page.
import fs from 'node:fs';
import path from 'node:path';
import yaml from 'js-yaml';
import { loadMkdocs, mkdocsUrl } from './mkdocs.mjs';
import { compileCheck } from './compile.mjs';
import { Report } from './run.mjs';
import { productCards } from './overview.mjs';

const posix = path.posix;

// The part's legacy map: legacy URL → page path (as in redirects.yaml).
function partPages(repoDir, part) {
  const file = path.join(repoDir, part, 'redirects.yaml');
  if (!fs.existsSync(file)) throw new Error(`Cloud part ${part}/ is not on this branch yet (no ${posix.join(part, 'redirects.yaml')}); convert it first`);
  const data = yaml.load(fs.readFileSync(file, 'utf8')) ?? {};
  return new Map((data.legacy ?? []).map((l) => [l.from, l.to]));
}

export async function convertFamily({ config, sourceRoot, repoDir, sourceRef, compile = true, log = () => {} }) {
  const outDir = path.join(repoDir, config.slug);
  const report = new Report();
  const o = config.overview;
  // No `tree` (a Docusaurus source has no family home page): the overview
  // is the intro and the product cards only.
  const mk = o.tree ? loadMkdocs(path.resolve(sourceRoot, o.tree)) : { nav: [], config: {} };
  const labelToSrc = new Map();
  const walk = (nodes, trail) => {
    for (const n of nodes) {
      if (n.kind === 'page') labelToSrc.set([...trail, n.label].join('|').toLowerCase(), n.src.trim().replace(/^\.?\//, ''));
      if (n.kind === 'section') walk(n.children, [...trail, n.label]);
    }
  };
  walk(mk.nav, []);
  const maps = new Map(config.parts.map((p) => [p.docSpace, partPages(repoDir, p.docSpace)]));
  const partLink = (part, page) => `docs:${part}/cloud/${page ? `${page.replace(/\/$/, '')}/` : ''}`;

  const lines = [];
  if (o.intro) lines.push(o.intro, '');
  lines.push(...productCards(config.parts, repoDir));
  let cards = 0;
  for (const block of mk.config.extra?.home_page_cards ?? []) {
    for (const section of block.section ?? []) {
      lines.push(`## ${section.title}`, '');
      for (const item of section.list_items ?? []) {
        const url = String(item.url);
        if (/^https?:\/\//.test(url)) {
          lines.push(`- [${item.title}](${url})`);
          continue;
        }
        const src = labelToSrc.get(url.toLowerCase());
        const legacy = src ? `${o.legacyBase}${mkdocsUrl(src)}` : null;
        const hit = legacy ? config.parts.map((p) => [p.docSpace, maps.get(p.docSpace).get(legacy)]).find(([, to]) => to !== undefined) : null;
        if (hit) {
          lines.push(`- [${item.title}](${partLink(hit[0], hit[1])})`);
          cards++;
        } else {
          lines.push(`- ${item.title}`);
          report.add('home', 'index', `home page card "${item.title}" (${url}) has no page in any Cloud part; written without a link`);
        }
      }
      lines.push('');
    }
  }
  const front = {
    title: config.docspace.displayName,
    description: o.description,
    type: 'concept',
    // Its link sections are drawn as cards (Extension points: Page layouts).
    layout: 'overview',
    sidebar_label: 'Overview',
    sidebar_position: 1,
  };

  // Regenerate the Doc space directory.
  for (const p of ['docs', 'partials', 'assets', '.migration']) fs.rmSync(path.join(outDir, p), { recursive: true, force: true });
  fs.mkdirSync(path.join(outDir, 'docs'), { recursive: true });
  const index = path.join(outDir, 'docs', 'index.mdx');
  fs.writeFileSync(index, `---\n${yaml.dump(front, { lineWidth: -1 })}---\n\n${lines.join('\n').replace(/\n+$/, '\n')}`);
  const generated = `# Generated by the WSO2 Docs converter from ${sourceRef}; during the Pilot,\n# change it in migration/products/ of wso2/docs-platform, not here.\n`;
  fs.writeFileSync(path.join(outDir, 'docspace.yaml'), `# Doc space manifest (schemas/docspace.schema.json in wso2/docs-platform).\n${generated}${yaml.dump(config.docspace, { lineWidth: -1 })}`);
  fs.writeFileSync(path.join(outDir, 'editions.yaml'), `# Per-Edition variables ({edition.*} in pages).\n${generated}${yaml.dump(config.editions, { lineWidth: -1 })}`);
  // The family's legacy home stays mapped to the part's home by the part's
  // own redirect map; the Cloud tree build decides how the two combine.
  fs.writeFileSync(path.join(outDir, 'redirects.yaml'), `# Page moves (from → to, both page paths) and legacy URL maps.\n${generated}${yaml.dump({ moves: [], legacy: [] })}`);

  let failures = [];
  if (compile) {
    log('Compiling 1 MDX file…');
    failures = await compileCheck([index]);
    for (const f of failures) report.add('compile', posix.relative(outDir, f.file), `${f.line ? `line ${f.line}: ` : ''}${f.message}`);
  }
  const summary = {
    source: sourceRef, edition: 'cloud', legacyBase: o.legacyBase, navPages: 0,
    parts: config.parts.map((p) => p.docSpace),
    stats: { pages: 1, partials: 0, apiPages: 0, images: 0, cardLinks: cards, acceptedByOverrides: 0 },
    issues: report.byKind(), compileFailures: failures.length, overrides: { patches: 0, patchesApplied: 0, accepted: 0 },
  };
  fs.mkdirSync(path.join(outDir, '.migration'), { recursive: true });
  fs.writeFileSync(path.join(outDir, '.migration', 'report.json'), `${JSON.stringify({ summary, items: report.items }, null, 2)}\n`);
  fs.writeFileSync(path.join(outDir, '.migration', 'report.md'), [
    `# Conversion report: ${config.docspace.displayName}`, '',
    `Converted from \`${sourceRef}\`: the family-level overview, ${o.tree ? `from the legacy home page's cards (${cards} linked into ${summary.parts.join(', ')})` : `the intro and a card per Cloud part (${summary.parts.join(', ')}); the source has no family home page`}.`, '',
    ...(report.items.length ? report.items.map((i) => `- **${i.kind}** ${i.file ?? ''}: ${i.message}`) : ['Nothing outstanding.']), '',
  ].join('\n'));
  return { summary, report, failures };
}
