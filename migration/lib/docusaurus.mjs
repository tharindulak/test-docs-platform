// Reads one version of a Docusaurus site the way Docusaurus does (Migration
// from Docusaurus sources, ticket 19): the version's docs (`docs/` is `next`,
// `versioned_docs/version-<v>/` a release), their ids and legacy URLs, and
// its sidebar as a tree of categories and docs. Then plans where every doc
// lands in the Content repo: the sidebar's top level is re-filed into the
// sidebar skeleton (the product's topLevel table), every category below it
// becomes a folder, and sidebar order becomes sidebar_position.
//
// The sidebar comes from versioned_sidebars/version-<v>-sidebars.json, or for
// `next` from sidebars.{json,ts,js}: a .ts or .js file is never run. Its
// object literal is parsed, and only literals are read (no code runs); when
// that fails, the sidebar falls back to the folders, as `autogenerated` does.
import fs from 'node:fs';
import path from 'node:path';
import yaml from 'js-yaml';
import matter from 'gray-matter';
import { unified } from 'unified';
import remarkParse from 'remark-parse';
import remarkMdx from 'remark-mdx';
import { docUrl } from './layout.mjs';
import { fileSlug, sentenceCase } from './slug.mjs';

const posix = path.posix;
const DOC = /\.mdx?$/;
const dirOf = (p) => (p.includes('/') ? p.slice(0, p.lastIndexOf('/')) : '');
const baseOf = (p) => p.slice(p.lastIndexOf('/') + 1);

// Docusaurus's number prefixes (01-intro.md): stripped from ids and URLs.
export function numberPrefix(name) {
  if (/^\d+[-_.]\d+/.test(name)) return { filename: name, numberPrefix: undefined }; // a date or version
  const m = /^(\d+)\s*[-_.]+\s*([^-_.\s].*)$/.exec(name);
  return m ? { filename: m[2], numberPrefix: Number(m[1]) } : { filename: name, numberPrefix: undefined };
}

// Where a version lives in the site: docs/ and the sidebars file for `next`,
// versioned_docs/ and versioned_sidebars/ for a release.
export function versionPaths(siteDir, edition) {
  if (edition === 'next') {
    const sidebarFile = ['sidebars.json', 'sidebars.ts', 'sidebars.js', 'sidebars.mjs', 'sidebars.cjs'].map((f) => path.join(siteDir, f)).find((f) => fs.existsSync(f)) ?? null;
    return { docsDir: path.join(siteDir, 'docs'), sidebarFile };
  }
  return {
    docsDir: path.join(siteDir, 'versioned_docs', `version-${edition}`),
    sidebarFile: path.join(siteDir, 'versioned_sidebars', `version-${edition}-sidebars.json`),
  };
}

const isPartialPath = (rel) => rel.split('/').some((seg) => seg.startsWith('_'));

// Every doc of the version (partials, `_`-prefixed files and folders, apart),
// with its id, title, sidebar position and legacy URL (route below the
// version's base, no leading or trailing slash).
export function readDocs(docsDir) {
  const docs = new Map(); // id → doc
  const partials = [];
  const categories = new Map(); // dir ('' for the root) → _category_ metadata
  const walk = (rel) => {
    const abs = path.join(docsDir, rel);
    for (const e of fs.readdirSync(abs, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
      const r = rel ? `${rel}/${e.name}` : e.name;
      if (e.isDirectory()) {
        if (e.name !== 'node_modules') walk(r);
      } else if (/^_category_\.(json|ya?ml)$/.test(e.name)) {
        const text = fs.readFileSync(path.join(abs, e.name), 'utf8');
        categories.set(rel, e.name.endsWith('.json') ? JSON.parse(text) : yaml.load(text) ?? {});
      } else if (DOC.test(e.name)) {
        if (isPartialPath(r)) partials.push(r);
        else {
          const doc = readDoc(docsDir, r);
          docs.set(doc.id, doc);
        }
      }
    }
  };
  walk('');
  return { docs, partials, categories };
}

function readDoc(docsDir, src) {
  const text = fs.readFileSync(path.join(docsDir, src), 'utf8');
  const fm = matter(text).data ?? {};
  const dir = dirOf(src);
  const raw = baseOf(src).replace(DOC, '');
  const { filename, numberPrefix: prefix } = numberPrefix(raw);
  const baseId = fm.id !== undefined ? String(fm.id) : filename;
  const id = dir ? `${dir}/${baseId}` : baseId;
  const h1 = /^#\s+(.+?)\s*(?:\{#[\w-]+\})?\s*$/m.exec(matter(text).content)?.[1] ?? null;
  const lastDir = baseOf(dir).toLowerCase();
  const isIndex = ['index', 'readme', ...(dir ? [lastDir] : [])].includes(raw.toLowerCase());
  // The legacy route, as Docusaurus's getSlug makes it.
  const dirSlug = dir.split('/').filter(Boolean).map((s) => numberPrefix(s).filename).join('/');
  let route;
  if (typeof fm.slug === 'string') route = fm.slug.startsWith('/') ? fm.slug : posix.join('/', dirSlug, fm.slug);
  else route = isIndex ? `/${dirSlug}` : posix.join('/', dirSlug, baseId);
  return {
    id, src, dir, name: filename, fm, title: fm.title ?? h1 ?? filename, h1,
    position: fm.sidebar_position ?? prefix, isIndex,
    url: route.replace(/^\/+|\/+$/g, ''),
  };
}

// ---- Sidebars -----------------------------------------------------------------

// The value of an estree node made only of literals, or a thrown error.
function literalValue(n) {
  switch (n.type) {
    case 'Literal':
      if (n.regex || n.bigint !== undefined) throw new Error(`${n.raw} is not a plain literal`);
      return n.value;
    case 'TemplateLiteral':
      if (n.expressions.length) throw new Error('a template literal with an expression');
      return n.quasis.map((q) => q.value.cooked).join('');
    case 'UnaryExpression':
      if (n.operator === '-' && n.argument.type === 'Literal' && typeof n.argument.value === 'number') return -n.argument.value;
      throw new Error(`the ${n.operator} operator`);
    case 'ArrayExpression':
      return n.elements.map((e) => {
        if (!e || e.type === 'SpreadElement') throw new Error('a spread or hole');
        return literalValue(e);
      });
    case 'ObjectExpression': {
      const out = {};
      for (const p of n.properties) {
        if (p.type !== 'Property' || p.computed || p.method || p.kind !== 'init') throw new Error('an object property that is not a plain key and value');
        const key = p.key.type === 'Identifier' ? p.key.name : String(p.key.value);
        out[key] = literalValue(p.value);
      }
      return out;
    }
    default:
      throw new Error(`a ${n.type}`);
  }
}

// The object literal a sidebars.ts or .js file exports, read without running
// it: the literal after `const <name>[: Type] =`, `module.exports =` or
// `export default`. Returns null when it holds anything but literals.
export function parseSidebarsSource(text) {
  const code = text.replace(/\/\*[\s\S]*?\*\//g, (m) => m.replace(/[^\n]/g, ' ')).replace(/(^|[^:'"`])\/\/[^\n]*/g, (m, p) => p + ' '.repeat(m.length - p.length));
  const m = /(?:\b(?:const|let|var)\s+[\w$]+\s*(?::\s*[\w$.<>, ]+)?\s*=|module\.exports\s*=|export\s+default)\s*\{/.exec(code);
  if (!m) return null;
  const start = m.index + m[0].length - 1;
  let depth = 0;
  let end = -1;
  for (let i = start, q = null; i < code.length; i++) {
    const c = code[i];
    if (q) {
      if (c === '\\') i++;
      else if (c === q) q = null;
      continue;
    }
    if (c === '"' || c === "'" || c === '`') q = c;
    else if (c === '{') depth++;
    else if (c === '}' && --depth === 0) { end = i + 1; break; }
  }
  if (end < 0) return null;
  // MDX's expression parser gives the estree without a new dependency.
  try {
    const tree = unified().use(remarkParse).use(remarkMdx).parse(`{${code.slice(start, end).replace(/\n/g, ' ')}}`);
    const expr = tree.children[0];
    if (expr?.type !== 'mdxFlowExpression') return null;
    const body = expr.data?.estree?.body ?? [];
    if (body.length !== 1 || body[0].type !== 'ExpressionStatement') return null;
    return literalValue(body[0].expression);
  } catch {
    return null;
  }
}

// The version's sidebar config and how it was read.
export function loadSidebars(sidebarFile) {
  if (!sidebarFile) return { config: null, how: 'no sidebars file: folders' };
  const text = fs.readFileSync(sidebarFile, 'utf8');
  if (sidebarFile.endsWith('.json')) return { config: JSON.parse(text), how: `${path.basename(sidebarFile)} (JSON)` };
  const config = parseSidebarsSource(text);
  return config
    ? { config, how: `${path.basename(sidebarFile)} (its object literal parsed, not run)` }
    : { config: null, how: `${path.basename(sidebarFile)} could not be read without running it: folders and sidebar_position` };
}

// An autogenerated sidebar slice, as Docusaurus's DefaultSidebarItemsGenerator
// builds it: categories from folders and _category_ files, a folder's index,
// README or same-name doc as its link, sorted by position then file name.
export function autogenerate(docs, categories, dirName = '.') {
  const all = [...docs.values()];
  const inDir = all.filter((d) => dirName === '.' || d.dir === dirName || d.dir.startsWith(`${dirName}/`));
  const root = {};
  for (const d of inDir) {
    const crumbs = dirName === '.' ? d.dir.split('/').filter(Boolean) : d.dir === dirName ? [] : d.dir.slice(dirName.length + 1).split('/');
    let cur = root;
    for (const c of crumbs) cur = (cur[c] ??= {});
    cur[baseOf(d.src)] = d.id;
  }
  const byId = (id) => docs.get(id);
  const docItem = (id, source) => {
    const d = byId(id);
    return { kind: 'doc', id, label: d.fm.sidebar_label ?? null, position: d.position, source };
  };
  const category = (dir, fullPath, folderName) => {
    const meta = categories.get(dirName === '.' ? fullPath : posix.join(dirName, fullPath));
    const items = Object.entries(dir).map(([k, v]) => (typeof v === 'object' ? category(v, `${fullPath}/${k}`, k) : docItem(v, k)));
    let linked;
    const link = meta?.link;
    if (link === undefined) linked = items.find((i) => i.kind === 'doc' && byId(i.id).isIndex);
    else if (link?.type === 'doc') {
      linked = items.find((i) => i.kind === 'doc' && baseOf(i.id) === link.id) ?? (byId(link.id) ? { id: link.id } : undefined);
    }
    const linkedDoc = linked ? byId(linked.id) : null;
    const { filename, numberPrefix: prefix } = numberPrefix(folderName);
    return {
      kind: 'category',
      label: meta?.label ?? linkedDoc?.fm.sidebar_label ?? linkedDoc?.title ?? filename,
      linkId: linkedDoc?.id ?? null,
      generatedIndex: link?.type === 'generated-index',
      items: items.filter((i) => !(i.kind === 'doc' && i.id === linkedDoc?.id)),
      position: meta?.position ?? linkedDoc?.position ?? prefix,
      source: folderName,
    };
  };
  const sort = (items) => items
    .map((i) => (i.kind === 'category' ? { ...i, items: sort(i.items) } : i))
    .map((i, n) => ({ i, n }))
    .sort((a, b) => (a.i.position ?? Infinity) - (b.i.position ?? Infinity) || (a.i.source < b.i.source ? -1 : a.i.source > b.i.source ? 1 : a.n - b.n))
    .map(({ i }) => i);
  const strip = (items) => items.map(({ position, source, ...i }) => (i.kind === 'category' ? { ...i, items: strip(i.items) } : i));
  return strip(sort(Object.entries(root).map(([k, v]) => (typeof v === 'object' ? category(v, k, k) : docItem(v, k)))));
}

// A sidebar (explicit items, shorthand categories and autogenerated slices)
// as one tree of { kind: 'category', label, linkId, items } and
// { kind: 'doc', id, label } and { kind: 'link', href, label } nodes.
export function normalizeSidebar(items, docs, categories, issues = []) {
  const out = [];
  for (const item of items ?? []) {
    if (typeof item === 'string') out.push({ kind: 'doc', id: item, label: null });
    else if (item.type === 'doc' || item.type === 'ref') out.push({ kind: 'doc', id: item.id, label: item.label ?? null });
    else if (item.type === 'autogenerated') out.push(...autogenerate(docs, categories, item.dirName ?? '.'));
    else if (item.type === 'category') {
      out.push({
        kind: 'category', label: item.label,
        linkId: item.link?.type === 'doc' ? item.link.id : null,
        generatedIndex: item.link?.type === 'generated-index',
        items: normalizeSidebar(item.items, docs, categories, issues),
      });
    } else if (item.type === 'link') out.push({ kind: 'link', href: item.href, label: item.label });
    else if (item.type === 'html') issues.push({ kind: 'sidebar', message: 'an html sidebar item was dropped (folder sidebars hold pages only)' });
    else if (!item.type && typeof item === 'object') {
      // Shorthand: { "Label": [items] }.
      for (const [label, sub] of Object.entries(item)) out.push({ kind: 'category', label, linkId: null, items: normalizeSidebar(sub, docs, categories, issues) });
    }
  }
  return out;
}

// One version of the site, read: its docs, partials, sidebar tree and how
// the sidebar was read.
export function readVersion(siteDir, edition, { sidebar: sidebarId } = {}) {
  const { docsDir, sidebarFile } = versionPaths(siteDir, edition);
  if (!fs.existsSync(docsDir)) throw new Error(`${docsDir} does not exist: no ${edition} docs in this site`);
  const { docs, partials, categories } = readDocs(docsDir);
  const { config, how } = loadSidebars(sidebarFile);
  const issues = [];
  let raw;
  if (config) {
    const id = sidebarId ?? Object.keys(config)[0];
    if (!config[id]) throw new Error(`${sidebarFile} has no sidebar "${id}"`);
    raw = config[id];
  } else raw = [{ type: 'autogenerated', dirName: '.' }];
  const tree = normalizeSidebar(raw, docs, categories, issues);
  return { docsDir, docs, partials, categories, tree, sidebarHow: how, issues };
}

// ---- Layout --------------------------------------------------------------------

function commonDir(srcs) {
  if (!srcs.length) return null;
  const parts = srcs.map((s) => dirOf(s).split('/').filter(Boolean));
  const out = [];
  for (let i = 0; ; i++) {
    const seg = parts[0][i];
    if (seg === undefined || parts.some((p) => p[i] !== seg)) break;
    out.push(seg);
  }
  return out.join('/');
}

// Keep a source file name that is already a kebab-case slug, so URLs stay
// recognisable; otherwise slug it.
const slugKeep = (name) => (/^[a-z0-9]+(?:[-.][a-z0-9]+)*$/.test(name) ? name : fileSlug(name));

// Where every doc lands: { pages: id → page, categories: folder → { label,
// position }, excluded: [ids], issues }. A page is { id, src, target (path
// below docs/, no extension), url, position, sidebarLabel, inSidebar }.
// config: topLevel (top-level sidebar label → { folder } for a category's
// items, with its link doc at <folder>/index, or { page } for where a single
// doc or a category's link doc goes), skeleton, excluded (source folder
// prefixes left out of the Doc space), properNouns, home ('first-link': the
// first top-level category's link doc is the Edition home; 'first-doc': its
// first doc when it links none).
export function planDocusaurus({ tree, docs, config }) {
  const pages = new Map();
  const categories = new Map();
  const issues = [];
  const excluded = new Set();
  const names = new Map();
  const counters = new Map();
  const urls = new Map();
  const sectionSources = new Map(); // folder → the source dir it stands for
  const isExcluded = (src) => (config.excluded ?? []).some((f) => src === f || src.startsWith(f));
  const label = (l) => (l ? sentenceCase(String(l), config.properNouns) : null);
  const nextPos = (folder) => {
    const n = (counters.get(folder) ?? 0) + 1;
    counters.set(folder, n);
    return n;
  };
  const taken = (folder) => {
    if (!names.has(folder)) names.set(folder, new Set());
    return names.get(folder);
  };
  const ensureFolders = (folder) => {
    const segs = folder.split('/').filter(Boolean);
    for (let i = 1; i <= segs.length; i++) taken(segs.slice(0, i - 1).join('/')).add(segs[i - 1]);
  };
  // A free name in the folder. index, readme and the folder's own name are
  // kept for the folder's link page (Docusaurus makes them the category link).
  const claim = (folder, wanted, fallback) => {
    const set = taken(folder);
    const reserved = (n) => ['index', 'readme', baseOf(folder)].includes(n);
    // A doc named like its folder that is not the folder's link (`link: null`)
    // becomes the folder's overview page.
    for (const n of reserved(wanted) ? ['overview', `${wanted}-overview`] : [wanted, fallback]) {
      if (n && !set.has(n) && !reserved(n)) {
        set.add(n);
        return n;
      }
    }
    let i = 2;
    const stem = reserved(wanted) ? `${wanted}-overview` : wanted;
    let n = stem;
    while (set.has(n) || reserved(n)) n = `${stem}-${i++}`;
    set.add(n);
    return n;
  };
  const doc = (id, where) => {
    const d = docs.get(id);
    if (!d) issues.push({ kind: 'sidebar', message: `${where} names the doc "${id}", which does not exist; dropped` });
    return d;
  };
  const addPage = (d, target, { position = null, sidebarLabel = null, inSidebar = true, navPath = [] }) => {
    if (pages.has(d.id)) {
      issues.push({ kind: 'sidebar', src: d.src, message: `in the sidebar more than once; only the first entry (${pages.get(d.id).navPath.join(' > ')}) is kept` });
      return;
    }
    let url = docUrl(target);
    if (urls.has(url)) {
      issues.push({ kind: 'layout', src: d.src, message: `would share the route /${url} with ${urls.get(url)}; renamed` });
      target = `${target}-${slugKeep(d.name)}`;
      url = docUrl(target);
    }
    urls.set(url, d.src);
    pages.set(d.id, { id: d.id, src: d.src, target, url, position, sidebarLabel, inSidebar, navPath });
  };
  const srcsUnder = (node) => {
    if (node.kind === 'doc') return docs.has(node.id) ? [docs.get(node.id).src] : [];
    if (node.kind !== 'category') return [];
    return [...(node.linkId && docs.has(node.linkId) ? [docs.get(node.linkId).src] : []), ...node.items.flatMap(srcsUnder)];
  };
  const placeLink = (node, target, navPath) => {
    if (!node.linkId) return;
    const d = doc(node.linkId, `category "${navPath.join(' > ')}"`);
    if (!d) return;
    if (isExcluded(d.src)) { excluded.add(d.id); return; }
    ensureFolders(dirOf(target));
    taken(dirOf(target)).add(baseOf(target));
    addPage(d, target, { position: null, navPath });
  };
  const placeItems = (items, folder, srcDir, navPath) => {
    for (const item of items) {
      const p = [...navPath, item.label ?? item.id ?? ''];
      if (item.kind === 'link') {
        issues.push({ kind: 'sidebar', message: `sidebar link "${item.label}" → ${item.href} dropped (folder sidebars hold pages only)` });
        continue;
      }
      if (item.kind === 'doc') {
        const d = doc(item.id, `sidebar "${navPath.join(' > ')}"`);
        if (!d) continue;
        if (isExcluded(d.src)) { excluded.add(d.id); continue; }
        if (pages.has(d.id)) { addPage(d, '', { navPath: p }); continue; }
        const name = claim(folder, slugKeep(d.name), slugKeep(`${baseOf(d.dir)}-${d.name}`));
        const sidebarLabel = item.label ?? d.fm.sidebar_label ?? null;
        addPage(d, `${folder}/${name}`, { position: nextPos(folder), sidebarLabel: sidebarLabel ? label(sidebarLabel) : null, navPath: p });
        continue;
      }
      const srcs = srcsUnder(item).filter((s) => !isExcluded(s));
      if (!srcs.length) {
        for (const s of srcsUnder(item)) excluded.add([...docs.values()].find((d) => d.src === s).id);
        if (!srcsUnder(item).length) issues.push({ kind: 'sidebar', message: `sidebar category "${p.join(' > ')}" has no pages; dropped` });
        continue;
      }
      const c = commonDir(srcs);
      const inside = srcDir === '' ? c !== '' : c.startsWith(`${srcDir}/`);
      const childFolder = `${folder}/${claim(folder, inside ? slugKeep(numberPrefix(baseOf(c)).filename) : fileSlug(item.label), fileSlug(item.label))}`;
      categories.set(childFolder, { label: label(item.label), position: nextPos(folder) });
      if (item.generatedIndex) issues.push({ kind: 'sidebar', message: `category "${p.join(' > ')}" had a generated index page; the folder lists its pages instead` });
      sectionSources.set(childFolder, inside ? c : srcDir);
      placeLink(item, `${childFolder}/index`, p);
      placeItems(item.items, childFolder, inside ? c : srcDir, p);
    }
  };

  (config.skeleton ?? []).forEach((s, i) => categories.set(s.folder, { label: s.label, position: i + 1, skeleton: true }));
  // config.home 'first-doc': the first top-level category's first page is
  // its link (and so the Edition home) when no category links a page.
  if (config.home === 'first-doc') {
    const first = tree.find((n) => n.kind === 'category');
    const at = first && !first.linkId ? first.items.findIndex((i) => i.kind === 'doc') : -1;
    if (at >= 0) {
      tree = tree.map((n) => (n === first ? { ...n, linkId: n.items[at].id, items: n.items.filter((_, i) => i !== at) } : n));
      config = { ...config, home: 'first-link' };
    }
  }
  let homePlaced = false;
  for (const node of tree) {
    const nodeLabel = node.kind === 'doc' ? (node.label ?? docs.get(node.id)?.fm.sidebar_label ?? docs.get(node.id)?.title) : node.label;
    const srcs = srcsUnder(node);
    if (srcs.length && srcs.every(isExcluded)) {
      for (const s of srcs) excluded.add([...docs.values()].find((d) => d.src === s).id);
      continue;
    }
    const top = config.topLevel[nodeLabel];
    if (!top) throw new Error(`Top-level sidebar item "${nodeLabel}" has no entry in the product's topLevel table`);
    if (node.kind === 'link') {
      issues.push({ kind: 'sidebar', message: `top-level sidebar link "${node.label}" → ${node.href} dropped` });
      continue;
    }
    if (node.kind === 'doc') {
      const d = doc(node.id, 'the sidebar\'s top level');
      if (!d) continue;
      ensureFolders(dirOf(top.page));
      taken(dirOf(top.page)).add(baseOf(top.page));
      addPage(d, top.page, { position: top.page === 'index' ? null : nextPos(dirOf(top.page)), navPath: [nodeLabel] });
      continue;
    }
    const c = commonDir(srcs.filter((s) => !isExcluded(s))) ?? '';
    if (top.folder) {
      ensureFolders(top.folder);
      const parent = dirOf(top.folder);
      if (!categories.get(top.folder)?.skeleton) categories.set(top.folder, { label: label(node.label), position: nextPos(parent) });
      sectionSources.set(top.folder, c);
    }
    // The Edition home: the first top-level category's link doc (config.home
    // 'first-link'; a Docusaurus site's own home is a React page).
    const home = config.home === 'first-link' && !homePlaced && Boolean(node.linkId);
    if (home) homePlaced = true;
    placeLink(node, home ? 'index' : top.page ?? top.link ?? `${top.folder}/index`, [nodeLabel]);
    if (node.items.length && !top.folder) throw new Error(`Top-level sidebar category "${nodeLabel}" has pages besides its link; give it a folder in the topLevel table`);
    if (top.folder) placeItems(node.items, top.folder, c, [nodeLabel]);
  }

  // Docs in no sidebar: next to the section whose source folder is the
  // longest prefix of theirs, unlisted (built, but in no sidebar or search).
  const bySource = [...sectionSources.entries()].filter(([, s]) => s !== '').sort((a, b) => b[1].length - a[1].length);
  for (const d of docs.values()) {
    if (pages.has(d.id) || excluded.has(d.id)) continue;
    if (isExcluded(d.src)) { excluded.add(d.id); continue; }
    const hit = bySource.find(([, s]) => d.dir === s || d.dir.startsWith(`${s}/`));
    const folder = hit ? hit[0] : config.unlistedFolder ?? 'reference';
    const rest = hit ? d.dir.slice(hit[1].length).replace(/^\//, '') : d.dir;
    const targetDir = [folder, rest].filter(Boolean).join('/');
    ensureFolders(targetDir);
    for (let f = rest ? targetDir : null; f && f !== folder; f = dirOf(f)) if (!categories.has(f)) categories.set(f, { label: label(baseOf(f).replace(/[-_]+/g, ' ')), position: null });
    const name = claim(targetDir, slugKeep(d.name), slugKeep(`${baseOf(d.dir)}-${d.name}`));
    addPage(d, `${targetDir}/${name}`, { inSidebar: false, navPath: ['(not in the sidebar)'] });
  }
  return { pages, categories, excluded: [...excluded], issues };
}
