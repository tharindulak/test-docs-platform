// The warn-only prose lint on changed lines: Vale with the generated WSO2
// style, and cspell with the Platform dictionary plus the repo's words.txt.
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { spellCheckDocument } from 'cspell-lib';
import { VALE_DIR, checkUrl } from '../standards.mjs';
import { lineOf } from './content.mjs';

export function repoWords(root) {
  const file = path.join(root, 'words.txt');
  if (!fs.existsSync(file)) return [];
  return fs.readFileSync(file, 'utf8').split('\n').map((w) => w.trim()).filter((w) => w && !w.startsWith('#'));
}

export function findVale() {
  const candidates = [process.env.WSO2_DOCS_VALE, 'vale'].filter(Boolean);
  for (const bin of candidates) {
    const r = spawnSync(bin, ['--version'], { encoding: 'utf8' });
    if (r.status === 0) return { bin, version: r.stdout.trim().replace(/^vale version /, '') };
  }
  return null;
}

// A Vale config whose StylesPath holds the Platform's WSO2 style and a
// vocabulary of the Platform's words plus the repo's.
export function writeValeConfig(dir, words = []) {
  const styles = path.join(dir, 'styles');
  fs.rmSync(styles, { recursive: true, force: true });
  fs.mkdirSync(path.join(styles, 'config', 'vocabularies', 'WSO2'), { recursive: true });
  fs.cpSync(path.join(VALE_DIR, 'WSO2'), path.join(styles, 'WSO2'), { recursive: true });
  const accept = fs.readFileSync(path.join(VALE_DIR, 'config', 'vocabularies', 'WSO2', 'accept.txt'), 'utf8');
  fs.writeFileSync(path.join(styles, 'config', 'vocabularies', 'WSO2', 'accept.txt'), `${accept}${words.join('\n')}\n`);
  const ini = path.join(dir, '.vale.ini');
  fs.writeFileSync(ini, `# Generated by wso2-docs from the Platform's standards/.\nStylesPath = ${styles}\nMinAlertLevel = suggestion\nVocab = WSO2\n\n[*.{md,mdx}]\nBasedOnStyles = WSO2\n`);
  return ini;
}

const LEVEL = { error: 'error', warning: 'warning', suggestion: 'info' };

export function runVale(ctx, files, { all = false, blockingRules = [] } = {}) {
  const vale = findVale();
  if (!vale) return { skipped: 'Vale is not installed (see https://vale.sh/docs/install, or set WSO2_DOCS_VALE)', findings: [] };
  if (!files.length) return { findings: [], note: `Vale ${vale.version}` };
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'wso2-docs-vale-'));
  try {
    const ini = writeValeConfig(dir, repoWords(ctx.root));
    const r = spawnSync(vale.bin, ['--config', ini, '--output=JSON', '--no-exit', ...files], { cwd: ctx.root, encoding: 'utf8', maxBuffer: 256 * 1024 * 1024 });
    let alerts;
    try {
      alerts = JSON.parse(r.stdout || '{}');
    } catch {
      return { findings: [{ level: 'warning', file: null, line: 1, message: `Vale failed: ${(r.stderr || r.stdout).trim().slice(0, 300)}` }], note: `Vale ${vale.version}` };
    }
    const findings = [];
    for (const [file, list] of Object.entries(alerts)) {
      const rel = path.relative(ctx.root, path.resolve(ctx.root, file)).split(path.sep).join('/');
      for (const a of list) {
        if (!all && !ctx.onChangedLine(rel, a.Line)) continue;
        findings.push({
          level: LEVEL[a.Severity] ?? 'warning', file: rel, line: a.Line, column: a.Span?.[0],
          message: a.Message, rule: a.Check, link: a.Link || undefined,
          ...(blockingRules.includes(a.Check) ? { promoted: true } : {}),
        });
      }
    }
    return { findings, note: `Vale ${vale.version}` };
  } finally {
    fs.rmSync(dir, { recursive: true, force: true });
  }
}

// Code, JSX, expressions, URLs and front-matter keys are not prose.
const IGNORE = [
  /^(\s*)(`{3,}|~{3,})[^]*?^\1\2/gm,
  /`[^`\n]+`/g,
  /<\/?[A-Za-z][^>\n]*>/g,
  /\{[^}\n]*\}/g,
  /^(import|export)\s.*$/gm,
  /\]\([^)\n]*\)/g,
  /https?:\/\/\S+/g,
  /^[A-Za-z_]+:(?=\s)/gm,
  /<!--[^]*?-->/g,
];

export async function runSpelling(ctx, S, files, { all = false } = {}) {
  const words = [...S.words, ...repoWords(ctx.root), ...S.terminology.products.flatMap((p) => [p.name, p.short ?? '', ...(p.formerly ?? [])].join(' ').split(/\s+/))].filter(Boolean);
  const findings = [];
  for (const file of files) {
    const text = fs.readFileSync(path.join(ctx.root, file), 'utf8');
    const r = await spellCheckDocument(
      { uri: pathToFileURL(path.join(ctx.root, file)).href, text, languageId: 'markdown' },
      { generateSuggestions: true, noConfigSearch: true },
      { language: 'en-US', words, ignoreRegExpList: IGNORE, minWordLength: 4 },
    );
    for (const issue of r.issues) {
      const line = lineOf(text, issue.offset);
      if (!all && !ctx.onChangedLine(file, line)) continue;
      const sugg = (issue.suggestionsEx ?? issue.suggestions ?? []).slice(0, 3).map((s) => (typeof s === 'string' ? s : s.word));
      findings.push({
        level: 'warning', file, line, rule: 'spelling', link: checkUrl('spelling'),
        message: `Unknown word "${issue.text}"${sugg.length ? `; did you mean ${sugg.map((s) => `"${s}"`).join(', ')}?` : '.'} If it's right, add it to words.txt.`,
      });
    }
  }
  return { findings, note: 'cspell, en-US' };
}
