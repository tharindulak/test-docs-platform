// --- Author skills' reference files -------------------------------------------

// MDX page -> plain Markdown for the skills: no front matter or MDX comments,
// and relative links made absolute Contribute URLs.
function pageUrl(rel) {
  const route = path.posix.normalize(rel).replace(/(^|\/)index$/, '');
  return guideUrl(route ? `${route}/` : '');
}

function forSkill(rel) {
  const file = path.join(CONTRIBUTE_DIR, 'docs', rel);
  const src = outputs.get(file) ?? fs.readFileSync(file, 'utf8');
  const { data, content } = matter(src);
  const dir = path.posix.dirname(rel);
  const body = content
    .replace(/\{\/\*[^]*?\*\/\}\n*/g, '')
    .replace(/\]\(([^):#]+)\.mdx(#[^)]*)?\)/g, (_, p, hash = '') => `](${pageUrl(path.posix.join(dir, p))}${hash})`)
    .replace(/\]\(#([^)]+)\)/g, (_, a) => `](${pageUrl(rel.replace(/\.mdx$/, ''))}#${a})`)
    .replace(/ \{#[\w-]+\}$/gm, '');
  return `# ${data.title}\n\nSource: ${pageUrl(rel.replace(/\.mdx$/, ''))}\n${body.replace(/^\n+/, '\n')}`;
}

// One heading level down, outside code fences, so each page nests under the file's title.
function demote(md) {
  let fence = null;
  return md.split('\n').map((line) => {
    const f = /^(`{3,}|~{3,})/.exec(line);
    if (f) fence = fence === null ? f[1] : (line.startsWith(fence) ? null : fence);
    return fence === null && !f && /^#{1,5} /.test(line) ? `#${line}` : line;
  }).join('\n');
}

const standardsRef = `<!-- ${GENERATED} -->
# WSO2 Docs standards

The rules the author skills apply, generated from the Platform's standards source. They match what \`npx @wso2/docs check\` enforces and what the Contribute guide publishes.

${[
  forSkill('reference/style-guide.mdx'),
  forSkill('reference/terminology.mdx'),
  forSkill('concepts/page-types.mdx').replace(/<details>[^]*?<\/details>\n*/g, ''),
  forSkill('guides/write-for-several-editions.mdx'),
  forSkill('reference/admonitions.mdx'),
  forSkill('reference/front-matter.mdx'),
].map(demote).join('\n\n')}`;
for (const skill of ['check-my-changes', 'write-a-page']) emit(`skills/${skill}/references/standards.md`, `${standardsRef.trim()}\n`);
emit('skills/check-my-changes/references/checks.md', `<!-- ${GENERATED} -->\n${forSkill('reference/checks.mdx')}`);
for (const t of S.pageTypes) emit(`skills/write-a-page/references/templates/${t.id}.mdx`, fs.readFileSync(path.join(TEMPLATES_DIR, `${t.id}.mdx`), 'utf8'));

// --- Write or check -------------------------------------------------------------

const checkOnly = process.argv.includes('--check');
const stale = [];
for (const [file, content] of outputs) {
  const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
  if (current === content) continue;
  if (checkOnly) stale.push(path.relative(root, file));
  else {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, content);
  }
}
// Rules removed from the source must disappear from the package too.
for (const f of fs.existsSync(path.join(VALE_DIR, 'WSO2')) ? fs.readdirSync(path.join(VALE_DIR, 'WSO2')) : []) {
  const file = path.join(VALE_DIR, 'WSO2', f);
  if (outputs.has(file)) continue;
  if (checkOnly) stale.push(path.relative(root, file));
  else fs.rmSync(file);
}
if (checkOnly && stale.length) {
  console.error(`Stale standards outputs (run npm run standards):\n  ${stale.join('\n  ')}`);
  process.exitCode = 1;
} else {
  console.log(`${checkOnly ? 'Checked' : 'Wrote'} ${outputs.size} standards outputs from ${path.relative(root, STANDARDS_DIR)}/ (guide links use ${checkUrl('').replace(/#$/, '')}).`);
}
