// Generates site/src/css/oxygen-tokens.css from the pinned @wso2/oxygen-ui:
// every theme token as a CSS custom property, keyed on Docusaurus's own
// [data-theme] attribute, so readers download no MUI or Oxygen JavaScript.
// The package can't be loaded by plain Node (it imports CSS), so the theme is
// bundled with esbuild first.
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { build } from 'esbuild';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const outFile = path.join(root, 'site', 'src', 'css', 'oxygen-tokens.css');
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'node_modules', '@wso2', 'oxygen-ui', 'package.json'), 'utf8'));

const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'oxygen-tokens-'));
const entry = path.join(tmp, 'entry.mjs');
fs.writeFileSync(entry, `
import { createOxygenTheme, WSO2Theme } from '@wso2/oxygen-ui';
const theme = createOxygenTheme({ colorSchemeSelector: 'data-theme' }, WSO2Theme);
const sheets = theme.generateStyleSheets();
// MUI emits plain properties in camelCase (colorScheme); CSS needs kebab-case.
const prop = (k) => (k.startsWith('--') ? k : k.replace(/[A-Z]/g, (c) => '-' + c.toLowerCase()));
export const css = sheets.map((sheet) => Object.entries(sheet).map(([selector, vars]) =>
  selector + ' {\\n' + Object.entries(vars).map(([k, v]) => '  ' + prop(k) + ': ' + v + ';').join('\\n') + '\\n}').join('\\n')).join('\\n');
`);
const bundled = path.join(tmp, 'bundle.mjs');
await build({
  entryPoints: [entry],
  bundle: true,
  platform: 'node',
  format: 'esm',
  outfile: bundled,
  nodePaths: [path.join(root, 'node_modules')],
  loader: { '.css': 'empty', '.woff2': 'empty', '.woff': 'empty' },
  logLevel: 'error',
  banner: { js: "import { createRequire } from 'module'; const require = createRequire(import.meta.url);" },
});
const { css } = await import(pathToFileURL(bundled).href);

// Platform aliases: stable names the Infima mapping in custom.css uses, so an
// Oxygen rename touches this script, not the theme. primary-text is the darker
// shade that meets WCAG 2.2 AA for text on white; the orange is for accents.
const aliases = `
:root, [data-theme='light'] {
  --oxygen-palette-primary-text: var(--oxygen-palette-primary-dark);
  --oxygen-font-family: var(--oxygen-font-body1-family, 'Inter Variable', system-ui, sans-serif);
  --oxygen-shape-radius: var(--oxygen-shape-borderRadius, 8px);
}
[data-theme='dark'] {
  --oxygen-palette-primary-text: var(--oxygen-palette-primary-light);
}
`;

fs.writeFileSync(outFile, `/* GENERATED by scripts/build-tokens.mjs from @wso2/oxygen-ui ${pkg.version}. Do not edit. */\n${css}\n${aliases}`);
fs.rmSync(tmp, { recursive: true, force: true });
console.log(`Wrote ${path.relative(root, outFile)} (${css.split('\n').length} lines) from @wso2/oxygen-ui ${pkg.version}`);
